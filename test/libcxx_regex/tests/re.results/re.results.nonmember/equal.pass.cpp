// Ported from LLVM 242ccbf6b6d9d090762a87138c854f2d93b6ab60/re.results/re.results.nonmember/equal.pass.cpp
// See test/libcxx_regex/manifest.json for all adaptations to this test.
#include "adapter.h"
#include <cassert>
#include "test_macros.h"

void
test()
{
    libcxx_fixed_regex::match_results<const char*> m1;
    const char s[] = "abcdefghijk";
    assert(libcxx_fixed_regex::regex_search(s, m1, libcxx_fixed_regex::regex("cd((e)fg)hi")));
    libcxx_fixed_regex::match_results<const char*> m2;

    assert(m1 == m1);
    assert(m1 != m2);

    m2 = m1;

    assert(m1 == m2);
}

int main(int, char**)
{
    test();

  return 0;
}
